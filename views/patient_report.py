from reportlab.lib.enums import TA_CENTER

from database.hospital_database import get_connection
from utils.llm_client import get_llm

llm = get_llm()


# ----------------------------------------------------------
# Load Patient Data
# ----------------------------------------------------------

def load_patients():

    conn = get_connection()

    df = pd.read_sql_query(
        "SELECT * FROM patients",
        conn
    )

    conn.close()

    return df


# ----------------------------------------------------------
# AI Medical Summary
# ----------------------------------------------------------

def generate_ai_summary(patient):

    prompt = f"""
You are an experienced hospital doctor.

Generate a professional discharge summary for this patient.

Patient Name: {patient['Name']}
Age: {patient['Age']}
Gender: {patient['Gender']}
Blood Group: {patient['Blood Type']}
Medical Condition: {patient['Medical Condition']}
Doctor: {patient['Doctor']}
Hospital: {patient['Hospital']}
Medication: {patient['Medication']}
Test Result: {patient['Test Results']}
Admission Type: {patient['Admission Type']}

Write a concise medical report in around 120 words.

Do not use bullet points.
Do not invent diseases.
Maintain a professional hospital tone.
"""

    try:

        response = llm.invoke(prompt)

        return response.content

    except Exception:

        return (
            "The patient received appropriate medical care and responded "
            "well to treatment. The patient's condition remained stable "
            "during hospitalization. Follow-up consultation and medication "
            "compliance are advised."
        )


# ----------------------------------------------------------
# PDF Generator
# ----------------------------------------------------------

def create_pdf(patient, summary):

    buffer = BytesIO()

    doc = SimpleDocTemplate(buffer)

    styles = getSampleStyleSheet()

    title_style = styles["Heading1"]
    title_style.alignment = TA_CENTER
    title_style.textColor = colors.darkblue

    heading = styles["Heading2"]

    normal = styles["BodyText"]

    story = []

    story.append(
        Paragraph(
            "Hospital AI Management System",
            title_style
        )
    )

    story.append(
        Paragraph(
            "Patient Medical Report",
            heading
        )
    )

    story.append(Spacer(1, 20))

    patient_data = [

        ["Patient Name", patient["Name"]],
        ["Age", str(patient["Age"])],
        ["Gender", patient["Gender"]],
        ["Blood Group", patient["Blood Type"]],
        ["Medical Condition", patient["Medical Condition"]],
        ["Doctor", patient["Doctor"]],
        ["Hospital", patient["Hospital"]],
        ["Admission Type", patient["Admission Type"]],
        ["Admission Date", patient["Date of Admission"]],
        ["Discharge Date", patient["Discharge Date"]],
        ["Medication", patient["Medication"]],
        ["Test Result", patient["Test Results"]],
        ["Insurance", patient["Insurance Provider"]],
        ["Billing Amount", str(patient["Billing Amount"])],
        ["Room Number", str(patient["Room Number"])]
    ]

    table = Table(
        patient_data,
        colWidths=[180, 280]
    )

    table.setStyle(

        TableStyle([

            (
                "GRID",
                (0, 0),
                (-1, -1),
                0.5,
                colors.grey
            ),

            (
                "BACKGROUND",
                (0, 0),
                (0, -1),
                colors.lightblue
            ),

            (
                "TEXTCOLOR",
                (0, 0),
                (0, -1),
                colors.black
            ),

            (
                "FONTNAME",
                (0, 0),
                (-1, -1),
                "Helvetica"
            ),

            (
                "BOTTOMPADDING",
                (0, 0),
                (-1, -1),
                8
            )

        ])
    )

    story.append(table)

    story.append(Spacer(1, 25))

    story.append(
        Paragraph(
            "<b>AI Medical Summary</b>",
            heading
        )
    )

    story.append(
        Paragraph(
            summary,
            normal
        )
    )

    story.append(Spacer(1, 20))
    story.append(Spacer(1, 25))

    story.append(
        Paragraph(
            "<b>Report Generated By</b>",
            heading
        )
    )

    story.append(
        Paragraph(
            """
Hospital AI Management System<br/>
AI Powered Healthcare Assistant<br/><br/>

This report has been automatically generated using the
Hospital AI Management System. The medical summary has
been generated with AI assistance and should be reviewed
by qualified healthcare professionals before clinical use.
            """,
            normal
        )
    )

    story.append(Spacer(1, 25))

    story.append(
        Paragraph(
            "<b>Authorized Signature</b>",
            heading
        )
    )

    story.append(
        Paragraph(
            "______________________________",
            normal
        )
    )

    story.append(
        Paragraph(
            "Hospital Administrator",
            normal
        )
    )

    doc.build(story)

    pdf = buffer.getvalue()

    buffer.close()

    return pdf


# ----------------------------------------------------------
# STREAMLIT PAGE
# ----------------------------------------------------------

def patient_report_page():

    st.title("📄 Patient Report Generator")

    st.write(
        "Generate a professional AI-powered hospital report."
    )

    df = load_patients()

    if df.empty:

        st.error("No patient records found.")

        return

    patient_name = st.selectbox(

        "Select Patient",

        df["Name"].tolist()

    )

    patient = df[df["Name"] == patient_name].iloc[0]

    st.divider()

    col1, col2 = st.columns(2)

    with col1:

        st.metric("Patient", patient["Name"])
        st.metric("Age", patient["Age"])
        st.metric("Gender", patient["Gender"])
        st.metric("Blood Group", patient["Blood Type"])
        st.metric("Doctor", patient["Doctor"])
        st.metric("Condition", patient["Medical Condition"])

    with col2:

        st.metric("Hospital", patient["Hospital"])
        st.metric("Admission", patient["Admission Type"])
        st.metric("Medication", patient["Medication"])
        st.metric("Test Result", patient["Test Results"])
        st.metric("Room", patient["Room Number"])
        st.metric(
            "Billing",
            f"${patient['Billing Amount']:,.2f}"
        )

    st.divider()

    if st.button(
        "🤖 Generate AI Medical Report",
        use_container_width=True
    ):

        with st.spinner(
            "Generating AI Medical Summary..."
        ):

            summary = generate_ai_summary(patient)

        st.success("Medical Summary Generated")

        st.subheader("📝 AI Medical Summary")

        st.write(summary)

        pdf = create_pdf(
            patient,
            summary
        )

        st.download_button(

            label="📥 Download Patient Report (PDF)",

            data=pdf,

            file_name=f"{patient['Name']}_Medical_Report.pdf",

            mime="application/pdf",

            use_container_width=True

        )

    st.divider()

    with st.expander("📋 Patient Record"):

        st.dataframe(
            pd.DataFrame([patient]),
            use_container_width=True,
            hide_index=True
        )